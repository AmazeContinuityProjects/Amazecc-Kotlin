package com.amazecc.app.shared.utils

import androidx.compose.runtime.Composable
import platform.CoreGraphics.CGRectMake
import platform.Foundation.NSURL
import platform.Foundation.NSTemporaryDirectory
import platform.Foundation.writeToFile
import platform.Foundation.toNSData
import platform.UIKit.UIActivityViewController
import platform.UIKit.UIApplication
import platform.UIKit.UIViewController
import platform.UIKit.UIWindow
import platform.UIKit.UIWindowScene

/**
 * Resolve the topmost presented view controller from the key window. `keyWindow` is deprecated
 * under the SwiftUI WindowGroup lifecycle and is often nil, so walk connected scenes instead and
 * fall back to any available window.
 */
private fun topViewController(): UIViewController? {
    val scenes = UIApplication.sharedApplication.connectedScenes
    val windows = scenes.mapNotNull { it as? UIWindowScene }
        .flatMap { scene -> scene.windows.mapNotNull { it as? UIWindow } }
    val key = windows.firstOrNull { it.isKeyWindow } ?: windows.firstOrNull() ?: return null
    var controller = key.rootViewController ?: return null
    while (true) {
        controller = controller.presentedViewController ?: break
    }
    return controller
}

/**
 * iOS has no Downloads directory the app can write to directly. Write the generated bytes to a
 * real temporary file and hand the user a system share sheet, from which "Save to Files" works.
 * This is a genuine action: the file exists on disk and the sheet is presented on the main actor.
 */
private fun writeAndPresent(fileName: String, bytes: ByteArray): Boolean = try {
    val directory = NSTemporaryDirectory().trimEnd('/')
    val path = "$directory/$fileName"
    if (!bytes.toNSData().writeToFile(path, atomically = true)) return false
    val fileUrl = NSURL.fileURLWithPath(path)
    val presenter = topViewController() ?: return false
    val sheet = UIActivityViewController(activityItems = listOf(fileUrl), applicationActivities = null)
    // iPad requires an anchor for a UIPopoverPresentationController; without this UIKit throws
    // NSInvalidArgumentException. On iPhone the popover controller is nil, so this is harmless.
    sheet.popoverPresentationController?.let { popover ->
        popover.sourceView = presenter.view
        popover.sourceRect = CGRectMake(0.0, 0.0, 1.0, 1.0)
    }
    presenter.presentViewController(sheet, animated = true, completion = null)
    true
} catch (_: Exception) {
    false
}

@Composable
actual fun rememberFileSaver(): (fileName: String, bytes: ByteArray) -> Boolean = { fileName, bytes ->
    writeAndPresent(fileName, bytes)
}

@Composable
actual fun rememberPdfOpener(): (fileName: String, bytes: ByteArray) -> Boolean = { fileName, bytes ->
    writeAndPresent(fileName, bytes)
}
