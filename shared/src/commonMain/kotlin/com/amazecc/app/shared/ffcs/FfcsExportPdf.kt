package com.amazecc.app.shared.ffcs

import com.amazecc.app.shared.pdf.PdfEngine
import com.amazecc.app.shared.pdf.PdfTextOptions

/**
 * D-182 — pure FFCS dossier PDF builder.
 *
 * Port of the web's vector dossier surface (`reference/06-import-export-share.md:313-338`,
 * `:392-394`) onto the app's existing [PdfEngine.buildTextPdf] seam. Everything is derived from
 * the real [TimetableState] values supplied by the caller: course rows carry code, title, type,
 * credits, slot tokens, venue and faculty, and every timetable ends with a real summary.
 *
 * No I/O, no clock, no random ids: the byte output is a deterministic function of the inputs, so
 * the host can hash/compare it before handing it to `rememberFileSaver`. `PdfEngine` deliberately
 * folds non-ASCII to `?` (WinAnsi-compatible, valid xref offsets); the JSON/HTML builders keep
 * UTF-8 instead.
 */
object FfcsExportPdf {

    /** Same 11pt / 15pt-leading / 48-line layout the report dossier pins. */
    private val OPTIONS = PdfTextOptions(
        fontSize = 11,
        leading = 15,
        startX = 36,
        startY = 812,
        linesPerPage = 48,
    )

    /** Build the complete PDF bytes for [timetables], titled [title]. */
    fun build(timetables: List<TimetableState>, title: String): ByteArray =
        PdfEngine.buildTextPdf(title, contentLines(timetables, title), OPTIONS)

    /**
     * The exact lines drawn into the PDF. Exposed (internal) so tests can assert on real rows
     * without parsing content streams, and so a host may prepend/append its own lines.
     */
    internal fun contentLines(timetables: List<TimetableState>, title: String): List<String> {
        val heading = title.trim().ifEmpty { "FFCS Dossier" }
        if (timetables.isEmpty()) {
            return listOf(
                heading,
                "",
                "No timetables to export.",
                "Generate a timetable in the FFCS planner first.",
            )
        }

        val lines = mutableListOf<String>()
        lines += heading
        lines += "Generated by AmazeCC FFCS Planner. Not an official institutional timetable."
        lines += ""

        timetables.forEachIndexed { index, timetable ->
            lines += "Timetable ${index + 1}: ${timetable.name.trim().ifEmpty { "(untitled)" }}"
            lines += "SUMMARY: ${timetable.courses.size} courses, " +
                "${timetable.metrics.halfDays} half-days, ${timetable.metrics.gaps} gaps"
            lines += "CODE | COURSE | TYPE | CR | SLOTS | VENUE | FACULTY"
            if (timetable.courses.isEmpty()) {
                lines += "(no courses in this timetable)"
            } else {
                timetable.courses.forEach { course ->
                    val slots = course.slots.joinToString("+").ifEmpty { "NIL" }
                    lines += listOf(
                        course.code,
                        course.title,
                        course.type,
                        course.credits,
                        slots,
                        course.venue,
                        course.faculty,
                    ).joinToString(" | ") { it.trim().ifEmpty { "-" } }
                }
            }
            lines += ""
        }
        return lines
    }
}

/** Convenience top-level alias matching the export-ladder API name. */
fun buildFfcsPdf(timetables: List<TimetableState>, title: String): ByteArray =
    FfcsExportPdf.build(timetables, title)
