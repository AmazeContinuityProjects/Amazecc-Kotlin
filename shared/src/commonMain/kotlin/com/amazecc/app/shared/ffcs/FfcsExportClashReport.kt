package com.amazecc.app.shared.ffcs

/**
 * D-182 — data passed to the clash-report builder. Every instance must come from a real overlap
 * in the caller's timetable; this module never invents courses, meetings or pairs.
 */
data class FfcsClashMeeting(
    /** Lower-case day id (`"mon"`) or a display form (`"Mon"`) — normalised for display. */
    val day: String,
    /** Clock occurrence, e.g. `"10:00"`. */
    val time: String,
)

/** One other course a real course clashes with, plus the concrete meetings that overlap. */
data class FfcsClashEntry(
    val code: String,
    val meetings: List<FfcsClashMeeting> = emptyList(),
)

/** One clash-report row: a real selected course and the real courses/meetings it overlaps with. */
data class FfcsClash(
    val course: AddedCourse,
    val clashesWith: List<FfcsClashEntry> = emptyList(),
)

/**
 * D-182 — plain-text approximation of the web clash report
 * (`reference/06-import-export-share.md:396-407`, `exportClashReport.ts:38-68,223-234`).
 *
 * The web PDF uses eight fixed A4-portrait columns whose widths sum to 171 mm. Because the pure
 * builder returns a [String] (the host decides whether to save it as `.txt` or feed the lines to a
 * PDF writer), the same eight columns are rendered here as fixed-width text cells: one character
 * per millimetre of the original column. [`CLASH_REPORT_COLUMNS`] sums to exactly 171. Every row is
 * derived from the supplied [FfcsClash] values; an empty input yields the honest "no clashes"
 * verdict and no fabricated rows.
 */
object FfcsExportClashReport {

    /** A4 portrait print width used by the web report; the sum is asserted in tests. */
    val CLASH_REPORT_COLUMNS: List<Int> = listOf(20, 40, 13, 8, 22, 20, 22, 26)

    val CLASH_REPORT_HEADERS: List<String> = listOf(
        "CODE", "COURSE", "TYPE", "CR", "SLOTS", "VENUE", "FACULTY", "CLASHES WITH",
    )

    /** Render [clashes] as a deterministic 171-column report with a real verdict. */
    fun build(clashes: List<FfcsClash>): String =
        lines(clashes).joinToString("\n", postfix = "\n")

    /**
     * The same report as discrete lines, so a host can feed them straight into a PDF writer
     * (e.g. `PdfEngine.buildTextPdf`) instead of saving the plain text.
     */
    fun lines(clashes: List<FfcsClash>): List<String> {
        val pairCount = clashes.sumOf { it.clashesWith.size }
        val verdict = when (pairCount) {
            0 -> "No clashes - all courses fit"
            1 -> "1 clash detected"
            else -> "$pairCount clashes detected"
        }
        val out = mutableListOf<String>()
        out += "FFCS CLASH REPORT"
        out += verdict
        out += "Generated by AmazeCC FFCS Planner. Not an official institutional report."
        out += ""
        out += renderRow(CLASH_REPORT_HEADERS)
        out += CLASH_REPORT_COLUMNS.joinToString(" ") { "-".repeat(it) }
        clashes.forEach { clash ->
            val course = clash.course
            out += renderRow(
                listOf(
                    course.code,
                    course.title,
                    course.type,
                    course.credits,
                    course.slots.joinToString("+").ifEmpty { "NIL" },
                    course.venue,
                    course.faculty,
                    formatClashCell(clash.clashesWith),
                )
            )
        }
        return out
    }

    /** `"CSE3001 (Mon 10:00, Wed 10:45); MAT2005 (Tue 08:00)"` — web `formatClashCell` parity. */
    private fun formatClashCell(entries: List<FfcsClashEntry>): String {
        if (entries.isEmpty()) return "-"
        return entries.joinToString("; ") { entry ->
            val meetings = entry.meetings.joinToString(", ") { meeting ->
                "${titleCase(meeting.day.trim())} ${meeting.time.trim()}"
            }
            if (meetings.isEmpty()) entry.code.trim() else "${entry.code.trim()} ($meetings)"
        }
    }

    /** `"mon"` / `"MON"` -> `"Mon"`; already-capitalised display forms are left alone. */
    private fun titleCase(day: String): String = when {
        day.isEmpty() -> day
        day.length == 1 -> day.uppercase()
        else -> day[0].uppercase() + day.substring(1).lowercase()
    }

    /**
     * Pad each cell to its 171-mm column width so rows stay aligned. Long real values are never
     * truncated: dropping the tail of a clash pair would hide the very data the report exists to
     * show, so a genuinely long cell simply overruns its nominal width.
     */
    private fun renderRow(cells: List<String>): String = buildString {
        cells.forEachIndexed { index, raw ->
            if (index > 0) append(' ')
            val value = raw.replace('\n', ' ').replace('\r', ' ').replace('\t', ' ').trim()
            val width = CLASH_REPORT_COLUMNS[index]
            append(if (value.length >= width) value else value + " ".repeat(width - value.length))
        }
    }
}

/** Convenience top-level alias matching the export-ladder API name. */
fun buildFfcsClashReport(clashes: List<FfcsClash>): String = FfcsExportClashReport.build(clashes)
